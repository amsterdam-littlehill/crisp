import { join } from "node:path";
import { generateParentGateway } from "../gateway/generator";
import { extractSkillFrontmatter } from "../manifest/frontmatter";
import { loadManifest, validateManifest } from "../manifest/io";
import type { CrpManifest, SkillEntry } from "../manifest/types";
